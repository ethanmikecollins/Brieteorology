export function updateTommy(){
  const frames = [0, 1, 2, 1, 3, 1, 2, 1]
    if (counter == 60){
        counter = 0;
        currentTommy += 1;
        if (currentTommy == frames.length){
            currentTommy = 0;
        }
    }else{
        counter += 1;
    }

    return TommyFrames[frames[currentTommy]]
}


export function renderAscii(text) {
    // Protect ASCII characters that HTML treats specially
    let html = text
        .replaceAll("&", "&amp;")
        .replaceAll("<", "&lt;")
        .replaceAll(">", "&gt;");

    // Convert our color markers into HTML
    html = html
        .replaceAll("[[green]]", '<span class="tommy-green">')
        .replaceAll("[[/green]]", "</span>")
        .replaceAll("[[brown]]", '<span class="tommy-brown">')
        .replaceAll("[[/brown]]", "</span>")
        .replaceAll("[[red]]", '<span class="therm-red">')
        .replaceAll("[[/red]]", "</span>")
        .replaceAll("[[blue]]", '<span class="humidity-blue">')
        .replaceAll("[[/blue]]", "</span>")
        .replaceAll("[[yellow]]", '<span class="sun-yellow">')
        .replaceAll("[[/yellow]]", "</span>")
        .replaceAll("[[gray]]", '<span class="cloud-gray">')
        .replaceAll("[[/gray]]", "</span>")

    return html;
}

